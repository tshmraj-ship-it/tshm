/* Active language - defaults to bn */
let currentLang = localStorage.getItem('madrasa_lang') || 'bn';

/**
 * Get translation string
 */
function t(key) {
  return TRANSLATIONS[currentLang][key] || TRANSLATIONS['bn'][key] || key;
}

/**
 * Translate all elements with data-i18n attribute
 */
function translatePage() {
  document.documentElement.lang = currentLang === 'bn' ? 'bn' : 'en';
  document.body.classList.toggle('lang-en', currentLang === 'en');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else if (el.hasAttribute('data-i18n-title')) {
      el.title = val;
    } else {
      el.textContent = val;
    }
  });

  // data-i18n-html for elements that need HTML (like prayer times with spans)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    el.innerHTML = t(key);
  });

  // Update lang toggle button
  const langBtns = document.querySelectorAll('.lang-btn');
  langBtns.forEach(btn => {
    btn.textContent = t('lang_toggle');
    btn.setAttribute('aria-label', `Switch to ${currentLang === 'bn' ? 'English' : 'Bangla'}`);
  });

  // Fire custom event for page-specific JS
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: currentLang } }));
}

/**
 * Switch language
 */
function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('madrasa_lang', lang);
  translatePage();
}

/**
 * Toggle language
 */
function toggleLanguage() {
  setLanguage(currentLang === 'bn' ? 'en' : 'bn');
}
